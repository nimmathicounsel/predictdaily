package com.nimmathi.predictdaily.model;

public class LocationInfo {
    private Double lat;
    private Double lon;
    private String zone;   

    public LocationInfo(Double lat, Double lon, String zone) {
        this.lat = lat;
        this.lon = lon;
        this.zone = zone;
    }

    public Double getLat() {
        return lat;
    }

    public void setLat(Double lat) {
        this.lat = lat;
    }

    public Double getLon() {
        return lon;
    }

    public void setLon(Double lon) {
        this.lon = lon;
    }

    public String getZone() {
        return zone;
    }

    public void setZone(String zone) {
        this.zone = zone;
    }
}
